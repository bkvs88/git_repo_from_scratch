def mean(a, b):
    c = (a + b) / 2
    print(f"Mean of {a} and {b} is : {c}")
    return c


def median(a, b):
    c = (a + b) / 2
    print(f"Median of {a} and {b} is : {c}")
    return c


def minimum(a, b):
    c = min(a, b)
    print(f"Minimum of {a} and {b} is : {c}")
    return c


def maximum(a, b):
    c = max(a, b)
    print(f"Maximum of {a} and {b} is : {c}")
    return c
